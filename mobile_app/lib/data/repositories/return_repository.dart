// المستودع — واجهة ثابتة تفوّض إلى الملفات المركزة بمجلد return/
// (تقسيم R18-D3a: النماذج النقية + التدفقات + الاستعلامات — بلا أي
// تغيير سلوك أو توقيع عام).
