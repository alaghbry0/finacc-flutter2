/// نوع الطرف — عميل أو مورد (FR-03-01 مقابل FR-03-03).
///
/// الموردون مرآة كاملة للعملاء باتجاه الشراء؛ هذا التعداد يوحّد الشاشات
/// والنماذج بين النوعين ويبقي التسميات والاتجاه المحاسبي صحيحاً.
library;

/// نوع الطرف.
enum PartyKind {
  /// عميل — رصيده الموجب دَين عليه لنا («المستحق لنا»).
  customer,

  /// مورد — رصيده الموجب ما تبقّى علينا دفعه («المستحق علينا»).
  supplier;

  /// هل هذا عميل؟ (اختصار تفريع الواجهات).
  bool get isCustomer => this == PartyKind.customer;
}
