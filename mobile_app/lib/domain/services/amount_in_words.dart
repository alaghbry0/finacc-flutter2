// محول العدد الصحيح — نقية خاصة
// ─────────────────────────────────────────────────────────────────────

/// يقرأ عدداً صحيحاً موجباً (≥ 1) بالكلمات: مجموعات ثلاثية من الأكبر
/// للأصغر، كل مجموعة تُقرأ ثم اسم رتبتها، والربط بينها بواو عند وجود
/// باقٍ غير صفري.
String _integerWords(int value) {
  // groups[0] = الآحاد، groups[1] = الآلاف، groups[2] = الملايين...
  final groups = <int>[];
  var rest = value;
  while (rest > 0) {
    groups.add(rest % 1000);
    rest ~/= 1000;
  }
  final parts = <String>[];
  for (var index = groups.length - 1; index >= 0; index--) {
    final group = groups[index];
    if (group == 0) continue;
    if (index == 0) {
      parts.add(_underThousand(group));
    } else {
      parts.add(_scaleGroup(group, index - 1));
    }
  }
  return parts.join(' و');
}

/// يقرأ مجموعة ثلاثية (1-999) بلا اسم رتبة: مئة/عشرون/واحد وعشرون
/// تُركَّب بالواو («مئة وواحد وعشرون»).
String _underThousand(int n) {
  final parts = <String>[];
  final hundreds = n ~/ 100;
  final tail = n % 100;
  if (hundreds > 0) {
    parts.add(_hundreds[hundreds]);
  }
  if (tail > 0) {
    if (tail < 10) {
      parts.add(_units[tail]);
    } else if (tail < 20) {
      parts.add(_teens[tail - 10]);
    } else {
      final unitDigit = tail % 10;
      final tensDigit = tail ~/ 10;
      parts.add(
        unitDigit == 0
            ? _tens[tensDigit]
            : '${_units[unitDigit]} و${_tens[tensDigit]}',
      );
    }
  }
  return parts.join(' و');
}

/// يقرأ مجموعة ثلاثية (1-999) مع اسم رتبتها [scaleIndex]
/// (0 = ألف، 1 = مليون، 2 = مليار، 3 = تريليون) — قواعد المطابقة
/// في القرار 3، والحكم على المنصوب/الجمع بآخر منزلتين.
String _scaleGroup(int group, int scaleIndex) {
  if (group == 1) {
    return _scaleSingular[scaleIndex];
  }
  if (group == 2) {
    return _scaleDual[scaleIndex];
  }
  final words = _underThousand(group);
  final tail = group % 100;
  if (tail >= 3 && tail <= 10) {
    return '$words ${_scalePlural[scaleIndex]}';
  }
  if (tail >= 11) {
    return '$words ${_scaleAccusative[scaleIndex]}';
  }
  // ذيل 0/1/2 فوق المئة: «مئة ألف»، «مئة وواحد ألف»، «مئتان ألف».
  return '$words ${_scaleSingular[scaleIndex]}';
}

/// 10 أسّ [n] لعدد صحيح صغير (0-3) — بلا اعتماديات.
int _pow10(int n) {
  var result = 1;
  for (var i = 0; i < n; i++) {
    result *= 10;
  }
  return result;
}
