/// أسماء الرتب مفردة: [ألف، مليون، مليار، تريليون] (الفهرس 0 =
/// الآلاف). التريليون شبكة أمان الحد الأعلى بعد التقريب (القرار 8).
const List<String> _scaleSingular = <String>[
  'ألف',
  'مليون',
  'مليار',
  'تريليون',
];

/// أسماء الرتب مثناة.
const List<String> _scaleDual = <String>[
  'ألفان',
  'مليونان',
  'ملياران',
  'تريليونان',
];

/// أسماء الرتب جمعاً (3-10).
const List<String> _scalePlural = <String>[
  'آلاف',
  'ملايين',
  'مليارات',
  'تريليونات',
];

/// أسماء الرتب مفردة منصوبة (المركب 11-99 — القرار 3).
const List<String> _scaleAccusative = <String>[
  'ألفًا',
  'مليونًا',
  'مليارًا',
  'تريليونًا',
];

/// يحوّل المبلغ إلى جملة عربية كاملة جاهزة للعرض تحت الرقم.
///
/// - [amount]: موجب ومحدد و≤ 999,999,999,999.99 وإلا رمي
///   [ArgumentError] برسالة عربية.
/// - [currencyName]: من `Currency.name` («ريال يمني») — يُذكر مفرداً
///   مرة واحدة (القرار 4).
/// - [currencyCode]: من `Currency.code` — يحدد اسم الوحدة الفرعية
///   (الخريطة أعلى الملف).
/// - [decimals]: منازل العملة (YER = 0 → لا كسر إطلاقاً — القرار 6).
///   القيم السالبة تُعامل صفراً وما فوق 3 يُقصّ إلى 3 (دقة أعمدة
///   NUMERIC(12,3) القصوى في المخطط).
/// - [withSuffix]: يضيف « فقط» في النهاية (الاصطلاح المحاسبي).
///
/// مثال: 5300 ريال يمني → «خمسة آلاف وثلاثمئة ريال يمني فقط»،
/// و125.50 ريال سعودي → «مئة وخمسة وعشرون ريال سعودي وخمسون هللة فقط».
String amountInWords({
  required double amount,
  required String currencyName,
  required String currencyCode,
  required int decimals,
  bool withSuffix = true,
}) {
  if (amount.isNaN || amount.isInfinite || amount < 0) {
    throw ArgumentError('المبلغ يجب أن يكون رقمًا موجبًا محددًا.');
  }
  if (amount > 999999999999.99) {
    throw ArgumentError(
      'المبلغ يتجاوز الحد الأقصى المدعوم للتفقيط (999,999,999,999.99).',
    );
  }
  final places = decimals < 0 ? 0 : (decimals > 3 ? 3 : decimals);

  // فصل الصحيح عن الكسر بمنازل العملة نفسها (قاعدة 5.4-9).
  var integer = 0;
  var fractionUnits = 0;
  if (places == 0) {
    // بلا منازل: المبلغ كله يُقرَّب لأقرب صحيح والكسر يُتخطى (القرار 6).
    integer = amount.round();
  } else {
    integer = amount.truncate();
    final scale = _pow10(places);
    fractionUnits = ((amount - integer) * scale).round();
    if (fractionUnits == scale) {
      // حمل التقريب: 2.999 SAR → 3.00 (القرار 7).
      integer += 1;
      fractionUnits = 0;
    }
  }

  // (أ) الجزء الصحيح + اسم العملة (القرار 4).
  final buffer = StringBuffer();
  if (integer == 0) {
    buffer.write('صفر $currencyName');
  } else if (integer == 1) {
    buffer.write('$currencyName واحد');
  } else if (integer == 2) {
    buffer.write('$currencyNameان');
  } else {
    buffer.write('${_integerWords(integer)} $currencyName');
  }

  // (ب) الكسر: الواو تلصق بأول كلمة الكسر وتفصل عمّا قبلها بمسافة
  // («ريال سعودي وخمسون هللة» — القراران 2 و5).
  if (fractionUnits > 0) {
    final subName = _subUnitNames[currencyCode];
    if (subName == null) {
      // رمز مجهول: الكسر رقماً غربياً بلا اسم وحدة (القرار 5).
      buffer.write(' و$fractionUnits');
    } else {
      buffer.write(' و${_integerWords(fractionUnits)} $subName');
    }
  }

  // (ج) اللاحقة المحاسبية.
  if (withSuffix) {
    buffer.write(' فقط');
  }
  return buffer.toString();
}

