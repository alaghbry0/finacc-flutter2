/// التفقيط العربي — تحويل المبلغ إلى كلمات عربية فصحى (V6-A).
///
/// مصدر التسمية: واجهات SIM للسندات تعرض «المبلغ بالكلمات» تحت الرقم
/// (نمط تفقيط الفواتير الخليجي/اليمني الشائع). المُدخل دائماً من
/// `Currency.name` (مثل «ريال يمني») و`Currency.code` و`Currency.decimals`
/// (YER = 0 بلا كسور — قاعدة 5.4-9).
///
/// ## القرارات النحوية الملزمة (فصحى مبسّطة، المعدود مذكر):
/// 1. **مئة لا مائة**: مئة/مئتان/ثلاثمئة/أربعمئة/خمسمئة/ستمئة/
///    سبعمئة/ثمانمئة/تسعمئة.
/// 2. **التركيب بالواو**: «واحد وعشرون»، «مئة وواحد وعشرون»، والربط بين
///    الرتب («خمسة آلاف وثلاثمئة») بواو مفصولة بمسافة؛ وواو الكسر كذلك
///    تلصق بأول كلمة الكسر وتفصل عمّا قبلها بمسافة («ريال سعودي
///    وخمسون هللة» — الإملاء العربي القياسي).
/// 3. **اسم الرتبة**: 1 → المفرد (ألف)، 2 → المثنى (ألفان)، 3-10 →
///    الجمع (آلاف)، المركب 11-99 → المفرد المنصوب (ألفًا/مليونًا/
///    مليارًا)، وما فوق المئة بالمفرد («مئة ألف»، «مئتان ألف»).
///    القرار عند المئة + مركب: يُحكم بآخر منزلتين (235 ألفًا،
///    101 ألف، 110 آلاف).
/// 4. **اسم العملة مفرد دائماً ويُذكر مرة واحدة في نهاية العدد**
///    («خمسة آلاف وثلاثمئة ريال يمني») — لا تصريف جمع للاسم المركب.
///    استثناء المطابقة: 1 → «{الاسم} واحد» (ريال يمني واحد)،
///    2 → «{الاسم}ان» (ريال يمنيان — المثنى المضاف بلا ألف فاصلة).
/// 5. **الكسر** يُقرأ بالكلمات العادية نفسها + اسم الوحدة الفرعية
///    كما هو («وخمسون هللة»، «وواحد سنت»)؛ الرمز المجهول مع كسر ≠ 0 →
///    «و{الكسر}» بأرقام غربية بلا اسم (المبالغ تُخزَّن بأرقام غربية —
///    اصطلاح `display.numerals`).
/// 6. **decimals = 0** → الكسر يُتخطى كلياً بعد تقريب المبلغ لأقرب
///    صحيح (قاعدة 5.4-9: التقريب بمنازل العملة نفسها — 5000.40 ريال
///    يمني → «خمسة آلاف ريال يمني فقط»).
/// 7. **حمل التقريب**: كسرٌ وصل حد العملة (2.999 ريال سعودي → 100
///    هللة) يُرفع للصحيح ويصفَّر الكسر — امتداد طبيعي للقاعدة 5.4-9.
/// 8. **شبكة أمان تريليون**: حد التفقيط 999,999,999,999.99 لكن تقريب
///    الحد الأعلى بعملة بلا منازل قد يبلغ 10^12 فيُقرأ «تريليون» بدل
///    الانكسار.
///
/// الدالة نقية صرفة (بلا IO) — قابلة للاختبار المباشر.
library;

/// أسماء الوحدات الفرعية حسب رمز العملة — خريطة ثابتة (قرار V6-A).
///
/// عملات البذر كلها مغطاة (YER/SAR/USD/AED) وما شاع في السوق الخليجي
/// واليمني. الرمز المجهول → لا اسم كسر (يُعرض رقمياً — انظر القرار 5).
const Map<String, String> _subUnitNames = <String, String>{
  'SAR': 'هللة',
  'USD': 'سنت',
  'AED': 'فلس',
  'YER': 'فلس',
  'EUR': 'سنت',
  'GBP': 'بنس',
  'KWD': 'فلس',
  'OMR': 'بيسة',
  'QAR': 'درهم',
  'BHD': 'فلس',
};

/// الوحدات 0-9 — المعدود مذكر (ريال/دولار/درهم كلها مذكرة).
const List<String> _units = <String>[
  'صفر',
  'واحد',
  'اثنان',
  'ثلاثة',
  'أربعة',
  'خمسة',
  'ستة',
  'سبعة',
  'ثمانية',
  'تسعة',
];

