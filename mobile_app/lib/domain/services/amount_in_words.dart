];

/// المئات 100-900 (الفهرس = عدد المئات) — «مئة» لا «مائة» (القرار 1).
const List<String> _hundreds = <String>[
  '',
  'مئة',
  'مئتان',
  'ثلاثمئة',
  'أربعمئة',
  'خمسمئة',
  'ستمئة',
  'سبعمئة',
  'ثمانمئة',
