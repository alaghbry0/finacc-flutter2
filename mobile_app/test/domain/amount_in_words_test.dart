/// اختبارات التفقيط العربي (V6-A) — `amountInWords`.
///
/// تحقق حرفي من السلاسل الكاملة وفق المواصفة الملزمة: مئة (لا مائة)،
/// التركيب بالواو، مطابقة اسم الرتبة (1/2/3-10/11-99/100+)، اسم العملة
/// مفرداً في نهاية العدد، الكسور بمنازل العملة (YER=0)، الرمز المجهول
/// رقمياً، وحدود الأخطاء (سالب/NaN/∞/فوق السقف).
library;

import 'package:flutter_test/flutter_test.dart';
import 'package:mobile_app/domain/services/amount_in_words.dart';

void main() {
  // اختصارات البذر: YER بلا منازل وSAR بمنازلتين (هللة).
  String yer(double amount, {bool withSuffix = true}) => amountInWords(
    amount: amount,
    currencyName: 'ريال يمني',
    currencyCode: 'YER',
    decimals: 0,
    withSuffix: withSuffix,
  );

  String sar(double amount, {bool withSuffix = true}) => amountInWords(
    amount: amount,
    currencyName: 'ريال سعودي',
    currencyCode: 'SAR',
    decimals: 2,
    withSuffix: withSuffix,
  );

  group('الوحدات والمراهقون والعشرات (YER)', () {
    test('صفر', () {
      expect(yer(0), 'صفر ريال يمني فقط');
    });

    test('واحد: الاسم ثم «واحد» (تمييز مفرد)', () {
      expect(yer(1), 'ريال يمني واحد فقط');
    });

    test('اثنان: المثنى المضاف بلا ألف فاصلة', () {
      expect(yer(2), 'ريال يمنيان فقط');
    });

    test('ثلاثة', () {
      expect(yer(3), 'ثلاثة ريال يمني فقط');
    });

    test('ثمانية', () {
      expect(yer(8), 'ثمانية ريال يمني فقط');
    });

    test('عشرة', () {
      expect(yer(10), 'عشرة ريال يمني فقط');
    });

    test('أحد عشر', () {
      expect(yer(11), 'أحد عشر ريال يمني فقط');
    });

    test('اثنا عشر', () {
      expect(yer(12), 'اثنا عشر ريال يمني فقط');
    });

    test('خمسة عشر (المراهق المركب)', () {
      expect(yer(15), 'خمسة عشر ريال يمني فقط');
    });

    test('عشرون', () {
      expect(yer(20), 'عشرون ريال يمني فقط');
    });

    test('واحد وعشرون (التركيب بالواو)', () {
      expect(yer(21), 'واحد وعشرون ريال يمني فقط');
    });

    test('اثنان وعشرون', () {
      expect(yer(22), 'اثنان وعشرون ريال يمني فقط');
    });

    test('تسعة وتسعون', () {
      expect(yer(99), 'تسعة وتسعون ريال يمني فقط');
    });
  });

  group('المئات (YER)', () {
    test('مئة (لا مائة)', () {
      expect(yer(100), 'مئة ريال يمني فقط');
    });

    test('مئة وواحد', () {
      expect(yer(101), 'مئة وواحد ريال يمني فقط');
    });

    test('مئة وعشرة', () {
      expect(yer(110), 'مئة وعشرة ريال يمني فقط');
    });

    test('مئة وأحد عشر', () {
      expect(yer(111), 'مئة وأحد عشر ريال يمني فقط');
    });

    test('مئتان', () {
      expect(yer(200), 'مئتان ريال يمني فقط');
    });

    test('ثلاثمئة وخمسون', () {
      expect(yer(350), 'ثلاثمئة وخمسون ريال يمني فقط');
    });

    test('تسعمئة وتسعة وتسعون', () {
      expect(yer(999), 'تسعمئة وتسعة وتسعون ريال يمني فقط');
    });
  });

  group('الآلاف (YER)', () {
    test('ألف', () {
      expect(yer(1000), 'ألف ريال يمني فقط');
    });

    test('ألف وواحد', () {
      expect(yer(1001), 'ألف وواحد ريال يمني فقط');
    });

    test('ألف ومئة', () {
      expect(yer(1100), 'ألف ومئة ريال يمني فقط');
    });

    test('ألفان', () {
      expect(yer(2000), 'ألفان ريال يمني فقط');
    });

    test('5300 — مثال المواصفة الحرفي', () {
      expect(yer(5300), 'خمسة آلاف وثلاثمئة ريال يمني فقط');
    });

    test('تسعة آلاف وتسعمئة وتسعة وتسعون', () {
      expect(yer(9999), 'تسعة آلاف وتسعمئة وتسعة وتسعون ريال يمني فقط');
    });

    test('عشرة آلاف (جمع)', () {
      expect(yer(10000), 'عشرة آلاف ريال يمني فقط');
    });

    test('أحد عشر ألفًا (منصوب)', () {
      expect(yer(11000), 'أحد عشر ألفًا ريال يمني فقط');
    });

    test('خمسة وعشرون ألفًا', () {
      expect(yer(25000), 'خمسة وعشرون ألفًا ريال يمني فقط');
    });

    test('مئة ألف (المعدود بعد الآلاف مفرد)', () {
      expect(yer(100000), 'مئة ألف ريال يمني فقط');
    });

    test('تسعمئة وتسعة وتسعون ألفًا وتسعمئة وتسعة وتسعون', () {
      expect(
        yer(999999),
        'تسعمئة وتسعة وتسعون ألفًا وتسعمئة وتسعة وتسعون ريال يمني فقط',
      );
    });
  });

  group('الملايين والمليارات (YER)', () {
    test('مليون', () {
      expect(yer(1000000), 'مليون ريال يمني فقط');
    });

    test('مليون وواحد', () {
      expect(yer(1000001), 'مليون وواحد ريال يمني فقط');
    });

    test('مليونان', () {
      expect(yer(2000000), 'مليونان ريال يمني فقط');
    });

    test('1235000 — الربط بين الرتب بالواو مع المنصوب', () {
      expect(yer(1235000), 'مليون ومئتان وخمسة وثلاثون ألفًا ريال يمني فقط');
    });

    test('مليار', () {
      expect(yer(1000000000), 'مليار ريال يمني فقط');
    });

    test('ملياران', () {
      expect(yer(2000000000), 'ملياران ريال يمني فقط');
    });
  });

  group('الكسور', () {
    test('عملة بلا منازل: 0.5 YER يُقرَّب لواحد (قاعدة 5.4-9)', () {
      expect(yer(0.5), 'ريال يمني واحد فقط');
    });

    test('عملة بلا منازل: 5000.40 YER → الكسر يُتخطى كليًا', () {
      expect(yer(5000.40), 'خمسة آلاف ريال يمني فقط');
    });

    test('125.50 SAR — مثال المواصفة الحرفي', () {
      expect(sar(125.50), 'مئة وخمسة وعشرون ريال سعودي وخمسون هللة فقط');
    });

    test('كسر دون صحيح: 0.5 SAR → «وخمسون هللة»', () {
      expect(sar(0.5), 'صفر ريال سعودي وخمسون هللة فقط');
    });

    test('أدنى كسر: 0.01 SAR → «وواحد هللة»', () {
      expect(sar(0.01), 'صفر ريال سعودي وواحد هللة فقط');
    });

    test('كسر مركب: 12.25 SAR → «وخمسة وعشرون هللة»', () {
      expect(sar(12.25), 'اثنا عشر ريال سعودي وخمسة وعشرون هللة فقط');
    });

    test('حمل التقريب: 2.999 SAR → ثلاثة ريال بلا كسر', () {
      expect(sar(2.999), 'ثلاثة ريال سعودي فقط');
    });

    test('999999999.99 SAR — الرتب الثلاث مع الكسر', () {
      expect(
        sar(999999999.99),
        'تسعمئة وتسعة وتسعون مليونًا وتسعمئة وتسعة وتسعون ألفًا '
        'وتسعمئة وتسعة وتسعون ريال سعودي وتسعة وتسعون هللة فقط',
      );
    });

    test('اسم عملة آخر مع وحدته الفرعية: 10.01 USD → «وواحد سنت»', () {
      expect(
        amountInWords(
          amount: 10.01,
          currencyName: 'دولار أمريكي',
          currencyCode: 'USD',
          decimals: 2,
        ),
        'عشرة دولار أمريكي وواحد سنت فقط',
      );
    });

    test('شذرات المواصفة بعملة الدولار: 0.01 و12.25 USD', () {
      expect(
        amountInWords(
          amount: 0.01,
          currencyName: 'دولار أمريكي',
          currencyCode: 'USD',
          decimals: 2,
        ),
        'صفر دولار أمريكي وواحد سنت فقط',
      );
      expect(
        amountInWords(
          amount: 12.25,
          currencyName: 'دولار أمريكي',
          currencyCode: 'USD',
          decimals: 2,
        ),
        'اثنا عشر دولار أمريكي وخمسة وعشرون سنت فقط',
      );
    });
  });

  group('رمز العملة المجهول', () {
    test('كسر ≠ 0 برمز مجهول → «و{الكسر}» رقماً غربياً بلا اسم', () {
      expect(
        amountInWords(
          amount: 100.63,
          currencyName: 'درهم مغربي',
          currencyCode: 'MAD',
          decimals: 2,
        ),
        'مئة درهم مغربي و63 فقط',
      );
    });

    test('كسر صفري برمز مجهول → لا ذكر للكسر إطلاقاً', () {
      expect(
        amountInWords(
          amount: 100,
          currencyName: 'ليرة',
          currencyCode: 'TRY',
          decimals: 2,
        ),
        'مئة ليرة فقط',
      );
    });
  });

  group('withSuffix', () {
    test('false بلا «فقط» (صحيح فقط)', () {
      expect(yer(5300, withSuffix: false), 'خمسة آلاف وثلاثمئة ريال يمني');
    });

    test('false مع كسر', () {
      expect(
        sar(125.50, withSuffix: false),
        'مئة وخمسة وعشرون ريال سعودي وخمسون هللة',
      );
    });
  });

  group('حدود السقف', () {
    test('الحد الأقصى نفسه 999,999,999,999.99 مدعوم بكسره', () {
      expect(
        amountInWords(
          amount: 999999999999.99,
          currencyName: 'ريال سعودي',
          currencyCode: 'SAR',
          decimals: 2,
        ),
        'تسعمئة وتسعة وتسعون مليارًا وتسعمئة وتسعة وتسعون مليونًا '
        'وتسعمئة وتسعة وتسعون ألفًا وتسعمئة وتسعة وتسعون ريال سعودي '
        'وتسعة وتسعون هللة فقط',
      );
    });

    test('تقريب الحد الأعلى بعملة بلا منازل → تريليون (شبكة الأمان)', () {
      expect(yer(999999999999.99), 'تريليون ريال يمني فقط');
    });
  });

  group('الأخطاء (ArgumentError برسائل عربية)', () {
    void expectInvalid(double amount) {
      expect(
        () => yer(amount),
        throwsA(
          isA<ArgumentError>().having(
            (error) => error.message,
            'message',
            'المبلغ يجب أن يكون رقمًا موجبًا محددًا.',
          ),
        ),
      );
    }

    test('مبلغ سالب', () {
      expectInvalid(-1);
    });

    test('Not-a-Number', () {
      expectInvalid(double.nan);
    });

    test('موجب ما لا نهاية', () {
      expectInvalid(double.infinity);
    });

    test('سالب ما لا نهاية', () {
      expectInvalid(double.negativeInfinity);
    });

    test('فوق السقف: 10^12', () {
      expect(
        () => yer(1000000000000),
        throwsA(
          isA<ArgumentError>().having(
            (error) => error.message,
            'message',
            'المبلغ يتجاوز الحد الأقصى المدعوم للتفقيط (999,999,999,999.99).',
          ),
        ),
      );
    });
  });
}
